# Plot the archived Fig. 4-related results, or explicitly choose newly recomputed results.
options(stringsAsFactors=FALSE)
if(.Platform$OS.type=='windows')invisible(try(Sys.setlocale('LC_CTYPE','English_United States.utf8'),silent=TRUE))
.src<-vapply(sys.frames(),function(fr)if(is.null(fr$ofile))''else as.character(fr$ofile)[1],character(1))
.arg<-grep('^--file=',commandArgs(FALSE),value=TRUE)
.file<-if(any(nzchar(.src)))tail(.src[nzchar(.src)],1)else if(length(.arg))sub('^--file=','',.arg[1])else''
MODULE<-if(nzchar(.file))dirname(dirname(normalizePath(.file,winslash='/',mustWork=TRUE)))else normalizePath(getwd(),winslash='/')
source(file.path(MODULE,'scripts','lib','release_utils.R'),encoding='UTF-8')
require_packages(c('ggplot2','patchwork'))
suppressPackageStartupMessages({library(ggplot2);library(patchwork)})
source(file.path(MODULE,'scripts','lib','plot_functions.R'),encoding='UTF-8')
args<-commandArgs(TRUE)
if(length(args)>1L||any(!args%in%c('--source=reference','--source=analysis')))stop('Use --source=reference or --source=analysis.')
source_mode<-if(length(args))sub('^--source=','',args)else'reference'
base<-if(source_mode=='reference')file.path(MODULE,'data','reference')else file.path(MODULE,'outputs','analysis')
results_file<-file.path(base,'mantel_results_by_genus.csv');matrix_dir<-file.path(base,'genus_matrices')
if(!file.exists(results_file))stop('Missing results. Run scripts/01_mantel_analysis.R before --source=analysis.')
res<-read.csv(results_file,check.names=FALSE)
stopifnot(all(c('Genus','Mantel_r','Mantel_p','N_species')%in%names(res)))
out<-file.path(MODULE,'outputs',if(source_mode=='reference')'figures_reference'else'figures_recomputed')
dir.create(out,showWarnings=FALSE,recursive=TRUE)
plots<-list();pair_list<-list()
for(i in seq_len(nrow(res))){
  genus<-res$Genus[i]
  if(!is.finite(res$Mantel_r[i])||!is.finite(res$Mantel_p[i]))next
  paths<-file.path(matrix_dir,paste0(genus,c('_species_genetic_distance.csv','_species_geographic_distance_km.csv')))
  if(any(!file.exists(paths)))stop('Missing archived species matrix for ',genus)
  genetic<-read_matrix_csv(paths[1]);geographic<-read_matrix_csv(paths[2])
  stopifnot(nrow(genetic)==res$N_species[i],identical(rownames(genetic),colnames(genetic)))
  stopifnot(identical(rownames(genetic),rownames(geographic)),identical(colnames(genetic),colnames(geographic)))
  pairs<-matrix_to_pairs(genetic,geographic)
  stopifnot(all(is.finite(pairs$GeneticDistance)),all(is.finite(pairs$GeographicDistance_km)))
  stopifnot(abs(cor(pairs$GeneticDistance,pairs$GeographicDistance_km)-res$Mantel_r[i])<1e-12)
  pair_list[[genus]]<-cbind(Genus=genus,pairs)
  plots[[genus]]<-plot_one_genus(genus,pairs,res$Mantel_r[i],res$Mantel_p[i])
  ggsave(file.path(out,paste0(genus,'_Mantel_scatter.pdf')),plots[[genus]],width=6,height=6)
  ggsave(file.path(out,paste0(genus,'_Mantel_scatter.png')),plots[[genus]],width=6,height=6,dpi=300)
}
if(!length(plots))stop('No estimable genus to plot.')
combined<-wrap_plots(plots,ncol=2)+plot_annotation(title='Genus-level Mantel scatter plots')
ggsave(file.path(out,'All_genera_Mantel_scatter_combined.pdf'),combined,width=11,height=4.5*ceiling(length(plots)/2))
ggsave(file.path(out,'All_genera_Mantel_scatter_combined.png'),combined,width=11,height=4.5*ceiling(length(plots)/2),dpi=600)
write.csv(do.call(rbind,pair_list),file.path(out,'plotted_species_pairs.csv'),row.names=FALSE)
write.csv(data.frame(Result_source=source_mode,P_value_source=if(source_mode=='reference')'archived_reference'else'seeded_reanalysis'),file.path(out,'plot_provenance.csv'),row.names=FALSE)
write.csv(res,file.path(out,'plotted_mantel_summary.csv'),row.names=FALSE)
capture.output(sessionInfo(),file=file.path(out,'sessionInfo.txt'))
cat('Plotted',length(plots),'genera; P-value source:',source_mode,'\n')
